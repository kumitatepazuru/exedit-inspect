def run(dll_path: str, headers: list[str], argv: list[str] | None = None) -> None:
    img = PEImage(dll_path)

    print(__doc__)

    print("\n" + "=" * 74)
    print("§1 オブジェクト版 func_proc ―― 画素には一切触らない")
    print("=" * 74)
    dump_range(img, FUNC_PROC_OBJ, 0x350, "func_proc (object)", annotations=NOTES)

    print("\n" + "=" * 74)
    print("§2 オブジェクト版ワーカー ―― 中心へ向かう線分の平均")
    print("=" * 74)
    dump_range(img, WORKER_OBJ, 0x3AB, "worker (object)", annotations=NOTES)

    print("\n" + "=" * 74)
    print("§3 フレーム版 func_proc ―― キャンバスが無いぶん短い")
    print("=" * 74)
    dump_range(img, FUNC_PROC_FRAME, 0x175, "func_proc (frame)", annotations=NOTES)

    print("\n" + "=" * 74)
    print("§4 参照している定数・共有アドレス")
    print("=" * 74)
    for va, what in (
        (0x1009A400, "8.0 ―― 距離を 1/8 画素単位にする"),
        (0x1009A3A0, "4096.0 ―― 色を sum_a で割るときのスケール"),
    ):
        print(f"  0x{va:08x}  f64 = {img.f64(va)!r:<10} {what}")
    for va, what in (
        (0x10091AD8, "CRT _ftol(0方向切り捨て)"),
        (0x10196748, "最大キャンバス幅(共有)"),
        (0x101920E0, "最大キャンバス高(共有)"),
        (0x10019160, "描画/ジオメトリ ルーチン(標準描画・拡張描画・グループ制御・"
                     "部分フィルタ・パーティクル出力と共有)"),
    ):
        print(f"  0x{va:08x}  {what}")
    print("\n  グローバル(全部このエフェクト専用、0x100d75a8-0x100d75c4 に連続):")
    for va, what in (
        (0x100D75A8, "cx = w/2 + X"),
        (0x100D75AC, "cy = h/2 + Y"),
        (0x100D75B0, "x1(拡張後の右端、排他)"),
        (0x100D75B4, "y1"),
        (0x100D75B8, "R' = trunc((1000-範囲)*R/1000) + R/2"),
        (0x100D75BC, "x0(拡張後の左端、<= 0)"),
        (0x100D75C0, "範囲 の生値"),
        (0x100D75C4, "y0"),
    ):
        print(f"  0x{va:08x}  {what}")


if __name__ == "__main__":
    run("data/exedit.auf", ["data/filter.h"])
