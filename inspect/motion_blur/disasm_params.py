def run(dll_path: str, headers: list[str], argv: list[str] | None = None) -> None:
    img = PEImage(dll_path)

    print(__doc__)

    print("\n" + "=" * 74)
    print("§1 func_proc ―― 時間を巻き戻すループ")
    print("=" * 74)
    dump_range(img, FUNC_PROC, 0x396, "func_proc", annotations=NOTES)

    print("\n" + "=" * 74)
    print("§2 ワーカー(オブジェクト、残像 OFF)")
    print("=" * 74)
    dump_range(img, WORKER_PLAIN, 0x21D, "worker (plain)", annotations=NOTES)

    print("\n" + "=" * 74)
    print("§3 ワーカー(オブジェクト、残像 ON)")
    print("=" * 74)
    dump_range(img, WORKER_AFTERIMAGE, 0x203, "worker (afterimage)", annotations=NOTES)

    print("\n" + "=" * 74)
    print("§4 ワーカー(フレーム)と 0x1000ad80")
    print("=" * 74)
    dump_range(img, WORKER_FRAME, 0x145, "worker (frame)", annotations=NOTES)
    dump_range(img, COMPOSITE_UNDER, 0x10A, "0x1000ad80 (下に合成)")

    print("\n" + "=" * 74)
    print("§5 参照している定数・共有アドレス")
    print("=" * 74)
    for va, what in (
        (0x1009A748, "1/3.14 ―― 減衰係数の分母"),
        (0x1009A428, "1.0"),
        (0x1009A3A0, "4096.0"),
    ):
        print(f"  0x{va:08x}  f64 = {img.f64(va)!r:<22} {what}"
              f"{'   (1/x = %.4f)' % (1 / img.f64(va)) if img.f64(va) else ''}")
    for va, what in (
        (0x1004D7D0, "名前付きキャッシュ(音声ディレイ / オブジェクト分割 / "
                     "カメラ制御 / パーティクル出力 と共有)"),
        (0x1004B200, "別オブジェクトとして描画(シャドー / テキスト / 画像ループ と共有)"),
        (0x1004CCF0, "指定時刻のフレームを描く(シーンチェンジ と共有)"),
        (0x1002B0D0, "オブジェクト添字の解決(グラデーション / 時間制御 と共有)"),
        (0x1000AD80, "1画素を「下に」合成(**モーションブラー専用**)"),
        (0x100B8C60, "オフスクリーン描画 func_proc へのポインタ(= 0x1008a520)"),
    ):
        print(f"  0x{va:08x}  {what}")
    print("\n  グローバル:")
    for va, what in (
        (0x101BAD34, "出力先バッファ"),
        (0x101BAD38, "A(蓄積側の重み、Q12)"),
        (0x101BAD3C, "入力元バッファ"),
        (0x101BAD40, "蓄積バッファ(キャッシュから)"),
        (0x101BAD48, "再入フラグ(オフスクリーン描画の再入ガード)"),
        (0x101A52E4, "出力中フラグ(exedit コア側。読むだけ)"),
    ):
        print(f"  0x{va:08x}  {what}")


if __name__ == "__main__":
    run("data/exedit.auf", ["data/filter.h"])
